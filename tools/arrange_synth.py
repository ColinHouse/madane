"""Build the まだね arrangement as a REAPER project and render it.

    python tools/arrange.py [version]

Python writes the samples, the guide vocal and a ReaScript with every note
embedded; REAPER builds the tracks and FX, renders the mix and stems, and saves
the project. If out/miku_<version>.wav exists it is used as the lead vocal.
"""
import subprocess
import sys
from pathlib import Path

import numpy as np
from scipy.io import wavfile

import build
import expression
import madane
import music
import reaper_run
import synth

ROOT = Path(__file__).resolve().parent.parent
VERSION = sys.argv[1] if len(sys.argv) > 1 else "v2"
WORK = ROOT / "reaper" / f"madane_{VERSION}"
SAMPLES = ROOT / "reaper" / "samples"
OUT = ROOT / "out"

PIANO_ROOTS = list(range(36, 85, 3))
DRUM_NOTES = {"kick": 36, "snare": 38, "hat": 42, "crash": 49}
DRUM_DB = {"kick": 0, "snare": -5, "hat": -15, "crash": -13}

# track name -> (volume dB, pan, reverb send dB or None)
MIX = {
    "Miku": (0.0, 0.0, -10),
    "Guide vocal (synth)": (0.0, 0.0, -10),
    "Piano": (-9.0, -0.1, -14),
    "Strings": (-5.0, 0.15, -9),
    "Strings high": (-9.0, -0.2, -8),
    "Bass": (-5.0, 0.0, None),
    "Drums": (-8.0, 0.0, -20),
}


def write_wav(path, x):
    wavfile.write(path, synth.SR, x.astype(np.float32))


def make_samples():
    SAMPLES.mkdir(parents=True, exist_ok=True)
    tones = {p: synth.piano(synth.hz(p), 5.0, 0.75) for p in PIANO_ROOTS}
    scale = 0.6 / max(np.abs(t).max() for t in tones.values())
    for p, t in tones.items():
        write_wav(SAMPLES / f"piano_{p}.wav", t * scale)
    for kind, fn in synth.DRUMS.items():
        x = fn(1.0)
        write_wav(SAMPLES / f"drum_{kind}.wav", x / np.abs(x).max() * 0.9)


def guide_vocal(sections, total_ticks, path):
    n = int((build.seconds(total_ticks) + 2) * synth.SR)
    cents, level = build.curves(sections, n)
    lead = [(build.seconds(x.start), build.seconds(x.length), x.pitch)
            for s in sections for x in s["notes"]]
    y = synth.lead_line(lead, n, cents, level)
    for s in sections:
        soft = s["feel"] in ("verse", "ochi", "outro")
        for ph in expression.phrases(s["notes"]):
            t = int((build.seconds(ph[0].start) - 0.36) * synth.SR)
            b = synth.breath(0.6 if soft else 0.9)
            if t > 0:
                y[t:t + len(b)] += b[: n - t] * 0.5
    write_wav(path, y / np.abs(y).max() * 0.8)


def high_strings(chords):
    """A sustained top line for the last chorus: nearest chord tone in C5..C6."""
    line, prev = [], 76
    for c in chords:
        if c.feel != "last":
            continue
        options = [p for p in range(72, 85) if p % 12 in c.tones]
        prev = min(options, key=lambda p: (abs(p - prev), p))
        line.append(music.Note(c.start, c.length, prev, 70))
    return line


def lua_notes(notes):
    return "{" + ",".join(f"{{{n.start / music.TPQ:.4f},{n.length / music.TPQ:.4f},"
                          f"{n.pitch},{n.velocity}}}" for n in notes) + "}"


def lua_string(s):
    return "[[" + str(s) + "]]"


def write_script(path, marks, total_ticks, tracks, miku, guide):
    total_qn = total_ticks / music.TPQ
    regions = ",".join(f"{{{build.seconds(m.start):.4f},"
                       f"{build.seconds(m.start + m.bars * music.BAR):.4f},{lua_string(m.name)}}}"
                       for m in marks)
    note_tables = ",\n  ".join(f'["{name}"] = {lua_notes(notes)}' for name, notes in tracks.items())
    mix = ",\n  ".join(f'["{k}"] = {{{v}, {p}, {"nil" if s is None else s}}}'
                       for k, (v, p, s) in MIX.items())
    piano_roots = ",".join(map(str, PIANO_ROOTS))
    drums = ",".join(f"{{{lua_string(k)}, {DRUM_NOTES[k]}, {DRUM_DB[k]}}}" for k in DRUM_NOTES)
    lua = LUA_TEMPLATE
    for key, value in {
        "@BPM@": str(madane.BPM), "@TOTAL_QN@": f"{total_qn:.4f}",
        "@END_S@": f"{build.seconds(total_ticks) + 4:.4f}", "@REGIONS@": regions,
        "@NOTES@": note_tables, "@MIX@": mix, "@PIANO_ROOTS@": piano_roots, "@DRUMS@": drums,
        "@SAMPLES@": lua_string(SAMPLES), "@WORK@": lua_string(WORK), "@OUT@": lua_string(OUT),
        "@VERSION@": VERSION, "@MIKU@": lua_string(miku) if miku else "nil",
        "@GUIDE@": lua_string(guide),
    }.items():
        lua = lua.replace(key, value)
    path.write_text(lua, encoding="utf-8")


LUA_TEMPLATE = r'''
-- Generated by tools/arrange.py; rebuilds the whole arrangement.
local SAMPLES, WORK, OUT = @SAMPLES@, @WORK@, @OUT@
local log = io.open(WORK .. "\\build_log.txt", "w")
local function say(s) log:write(s .. "\n"); log:flush() end

local NOTES = {
  @NOTES@
}
local MIX = {
  @MIX@
}
local REGIONS = {@REGIONS@}

local function parse(s)
  if s:find("inf") then return s:find("-inf") and -1e9 or 1e9 end
  return tonumber(s:match("[-+]?%d+%.?%d*")) or 0
end

-- Set a parameter by its displayed value (binary search on the normalized value).
local function set(tr, fx, idx, target)
  local function at(v) local _, s = reaper.TrackFX_FormatParamValueNormalized(tr, fx, idx, v, ""); return parse(s) end
  local lo, hi = 0.0, 1.0
  local rising = at(1) >= at(0)
  for _ = 1, 40 do
    local mid = (lo + hi) / 2
    if (at(mid) < target) == rising then lo = mid else hi = mid end
  end
  reaper.TrackFX_SetParamNormalized(tr, fx, idx, (lo + hi) / 2)
end

local function add_track(name)
  local i = reaper.CountTracks(0)
  reaper.InsertTrackAtIndex(i, true)
  local tr = reaper.GetTrack(0, i)
  reaper.GetSetMediaTrackInfo_String(tr, "P_NAME", name, true)
  return tr
end

local function add_midi(tr, notes)
  local item = reaper.CreateNewMIDIItemInProj(tr, 0, @TOTAL_QN@, true)
  local take = reaper.GetActiveTake(item)
  for _, n in ipairs(notes) do
    local s = reaper.MIDI_GetPPQPosFromProjQN(take, n[1])
    local e = reaper.MIDI_GetPPQPosFromProjQN(take, n[1] + n[2])
    reaper.MIDI_InsertNote(take, false, false, s, e, 0, n[3], n[4], true)
  end
  reaper.MIDI_Sort(take)
end

local function add_audio(tr, path)
  local item = reaper.AddMediaItemToTrack(tr)
  local take = reaper.AddTakeToMediaItem(item)
  local src = reaper.PCM_Source_CreateFromFile(path)
  reaper.SetMediaItemTake_Source(take, src)
  local len = reaper.GetMediaSourceLength(src)
  reaper.SetMediaItemInfo_Value(item, "D_POSITION", 0)
  reaper.SetMediaItemInfo_Value(item, "D_LENGTH", len)
end

-- MODE 1 plays the sample as is (drums); MODE 2 shifts it by semitones from the
-- range's start note, which plays at (lo - root) semitones (pitched instruments).
local function sampler(tr, file, lo, hi, root, gain_db)
  local fx = reaper.TrackFX_AddByName(tr, "ReaSamplOmatic5000 (Cockos)", false, -1)
  reaper.TrackFX_SetNamedConfigParm(tr, fx, "FILE0", file)
  reaper.TrackFX_SetNamedConfigParm(tr, fx, "DONE", "")
  reaper.TrackFX_SetNamedConfigParm(tr, fx, "MODE", lo == hi and "1" or "2")
  reaper.TrackFX_SetParamNormalized(tr, fx, 3, lo / 127)
  reaper.TrackFX_SetParamNormalized(tr, fx, 4, hi / 127)
  reaper.TrackFX_SetParamNormalized(tr, fx, 5, 0.5 + (lo - root) / 160)
  set(tr, fx, 0, gain_db)
  return fx
end

reaper.SetCurrentBPM(0, @BPM@, false)
for _, r in ipairs(REGIONS) do reaper.AddProjectMarker2(0, true, r[1], r[2], r[3], -1, 0) end

-- vocals
local miku = add_track("Miku")
if @MIKU@ then add_audio(miku, @MIKU@) end
local guide = add_track("Guide vocal (synth)")
add_audio(guide, @GUIDE@)
if @MIKU@ then reaper.SetMediaTrackInfo_Value(guide, "B_MUTE", 1) end
for _, tr in ipairs({miku, guide}) do
  local eq = reaper.TrackFX_AddByName(tr, "ReaEQ (Cockos)", false, -1)
  set(tr, eq, 12, 120)                      -- high pass
  set(tr, eq, 3, 350); set(tr, eq, 4, -2)   -- tame boxiness
  set(tr, eq, 9, 6000); set(tr, eq, 10, 2)  -- air
  local comp = reaper.TrackFX_AddByName(tr, "ReaComp (Cockos)", false, -1)
  set(tr, comp, 0, -20); set(tr, comp, 1, 3); set(tr, comp, 2, 8); set(tr, comp, 3, 150)
  set(tr, comp, 14, 6); set(tr, comp, 11, 2)
end

-- piano: one sampler per root, each covering root-1..root+1
local piano = add_track("Piano")
local roots = {@PIANO_ROOTS@}
for i, r in ipairs(roots) do
  local lo, hi = r - 1, r + 1
  if i == 1 then lo = 24 end
  if i == #roots then hi = 108 end
  local fx = sampler(piano, SAMPLES .. "\\piano_" .. r .. ".wav", lo, hi, r, 0)
  set(piano, fx, 2, -20)       -- velocity sensitivity
  set(piano, fx, 8, 16)        -- voices
  reaper.TrackFX_SetParamNormalized(piano, fx, 11, 1)   -- obey note-offs
  set(piano, fx, 10, 350)      -- release
end
local peq = reaper.TrackFX_AddByName(piano, "ReaEQ (Cockos)", false, -1)
set(piano, peq, 12, 45); set(piano, peq, 9, 7000); set(piano, peq, 10, -2)
add_midi(piano, NOTES["Piano"])

-- strings: soft saw/triangle pad, darkened
local function strings(name, notes)
  local tr = add_track(name)
  local fx = reaper.TrackFX_AddByName(tr, "ReaSynth (Cockos)", false, -1)
  set(tr, fx, 0, 450); set(tr, fx, 1, 800); set(tr, fx, 3, 0.5); set(tr, fx, 4, 0.3)
  set(tr, fx, 5, -12); set(tr, fx, 6, 4000); set(tr, fx, 9, -3)
  set(tr, fx, 7, 0.12); set(tr, fx, 8, 1200)
  local eq = reaper.TrackFX_AddByName(tr, "ReaEQ (Cockos)", false, -1)
  set(tr, eq, 12, 180); set(tr, eq, 9, 2500); set(tr, eq, 10, -8); set(tr, eq, 1, -2)
  add_midi(tr, notes)
  return tr
end
local str = strings("Strings", NOTES["Strings"])
local str_hi = strings("Strings high", NOTES["Strings high"])

-- bass
local bass = add_track("Bass")
local bfx = reaper.TrackFX_AddByName(bass, "ReaSynth (Cockos)", false, -1)
set(bass, bfx, 0, 4); set(bass, bfx, 1, 120); set(bass, bfx, 4, 0.45); set(bass, bfx, 5, -8)
set(bass, bfx, 6, 1500); set(bass, bfx, 9, -10); set(bass, bfx, 7, 0.15); set(bass, bfx, 8, 1200)
add_midi(bass, NOTES["Bass"])

-- drums: one sampler per sound
local drums = add_track("Drums")
for _, d in ipairs({@DRUMS@}) do
  local fx = sampler(drums, SAMPLES .. "\\drum_" .. d[1] .. ".wav", d[2], d[2], d[2], d[3])
  set(drums, fx, 2, -18)
  set(drums, fx, 8, 4)
end
add_midi(drums, NOTES["Drums"])

-- reverb bus
local verb = add_track("Reverb")
local rv = reaper.TrackFX_AddByName(verb, "ReaVerbate (Cockos)", false, -1)
set(verb, rv, 0, 0); reaper.TrackFX_SetParamNormalized(verb, rv, 1, 0)
set(verb, rv, 2, 85); set(verb, rv, 3, 55); set(verb, rv, 5, 25); set(verb, rv, 6, 7500); set(verb, rv, 7, 250)
reaper.SetMediaTrackInfo_Value(verb, "D_VOL", 10 ^ (-6 / 20))

-- levels, pans, sends
for i = 0, reaper.CountTracks(0) - 1 do
  local tr = reaper.GetTrack(0, i)
  local _, name = reaper.GetSetMediaTrackInfo_String(tr, "P_NAME", "", false)
  local m = MIX[name]
  if m then
    reaper.SetMediaTrackInfo_Value(tr, "D_VOL", 10 ^ (m[1] / 20))
    reaper.SetMediaTrackInfo_Value(tr, "D_PAN", m[2])
    if m[3] then
      local s = reaper.CreateTrackSend(tr, verb)
      reaper.SetTrackSendInfo_Value(tr, 0, s, "D_VOL", 10 ^ (m[3] / 20))
    end
  end
end

-- master bus: gentle glue + limiter
local master = reaper.GetMasterTrack(0)
local mc = reaper.TrackFX_AddByName(master, "ReaComp (Cockos)", false, -1)
set(master, mc, 0, -12); set(master, mc, 1, 2); set(master, mc, 2, 25); set(master, mc, 3, 250)
set(master, mc, 14, 6); set(master, mc, 11, 2)
local lim = reaper.TrackFX_AddByName(master, "ReaLimit (Cockos)", false, -1)
set(master, lim, 0, -4); set(master, lim, 1, -1)
say("tracks built: " .. reaper.CountTracks(0))

-- render the mix, then each track on its own
local function render(dir, pattern)
  reaper.GetSetProjectInfo_String(0, "RENDER_FILE", dir, true)
  reaper.GetSetProjectInfo_String(0, "RENDER_PATTERN", pattern, true)
  reaper.GetSetProjectInfo_String(0, "RENDER_FORMAT", "evaw", true)
  reaper.GetSetProjectInfo(0, "RENDER_SRATE", 44100, true)
  reaper.GetSetProjectInfo(0, "RENDER_CHANNELS", 2, true)
  reaper.GetSetProjectInfo(0, "RENDER_BOUNDSFLAG", 0, true)
  reaper.GetSetProjectInfo(0, "RENDER_STARTPOS", 0, true)
  reaper.GetSetProjectInfo(0, "RENDER_ENDPOS", @END_S@, true)
  reaper.Main_OnCommand(42230, 0)
end
render(OUT, "madane_reaper_@VERSION@")
say("mix rendered")
for i = 0, reaper.CountTracks(0) - 1 do
  local tr = reaper.GetTrack(0, i)
  local _, name = reaper.GetSetMediaTrackInfo_String(tr, "P_NAME", "", false)
  if name ~= "Reverb" and reaper.CountTrackMediaItems(tr) > 0 then
    reaper.SetMediaTrackInfo_Value(tr, "I_SOLO", 2)
    render(WORK .. "\\stems", (name:gsub("[^%w]", "_")))
    reaper.SetMediaTrackInfo_Value(tr, "I_SOLO", 0)
  end
end
say("stems rendered")
-- point the project's render settings back at the mix (without rendering again)
reaper.GetSetProjectInfo_String(0, "RENDER_FILE", OUT, true)
reaper.GetSetProjectInfo_String(0, "RENDER_PATTERN", "madane_reaper_@VERSION@", true)
reaper.Main_SaveProject(0, false)
say("saved")
log:close()
reaper.Main_OnCommand(40004, 0)
'''


def main():
    WORK.mkdir(parents=True, exist_ok=True)
    marks, parts, chords, hook, bars = music.layout(madane.SECTIONS)
    total = bars * music.BAR
    sections = build.sung_sections(parts)
    piano, pad, bass = music.accompaniment(chords)
    hits = music.drums(marks)

    make_samples()
    guide = WORK / f"guide_vocal_{VERSION}.wav"
    guide_vocal(sections, total, guide)
    miku = OUT / f"miku_{VERSION}.wav"

    drums = [music.Note(t, music.UNIT, DRUM_NOTES[k], v) for t, k, v in hits]
    tracks = {"Piano": piano + hook, "Strings": pad, "Strings high": high_strings(chords),
              "Bass": bass, "Drums": drums}
    script = WORK / f"build_{VERSION}.lua"
    write_script(script, marks, total, tracks, miku if miku.exists() else None, guide)
    # REAPER asks before overwriting renders, so clear the previous ones first
    for old in [OUT / f"madane_reaper_{VERSION}.wav", *(WORK / "stems").glob("*.wav")]:
        old.unlink(missing_ok=True)

    ok, secs, boot_log = reaper_run.run(script, WORK / f"madane_{VERSION}.rpp", timeout=600)
    print(f"REAPER {'finished' if ok else 'TIMED OUT'} in {secs:.0f}s; using "
          f"{'Miku vocal' if miku.exists() else 'synth guide vocal'}")
    print(boot_log)
    build_log = WORK / "build_log.txt"
    if build_log.exists():
        print(build_log.read_text(encoding="utf-8"))
    mix = OUT / f"madane_reaper_{VERSION}.wav"
    if mix.exists():
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(mix), "-b:a", "192k",
                        str(mix.with_suffix(".mp3"))], check=True)


if __name__ == "__main__":
    main()
